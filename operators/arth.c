#include <stdio.h>
int main (){
    int a=500;
    int b=50;
    printf("a+b: %d\n",a+b);
    printf("a-b: %d\n",a-b);
    printf("a*b: %d\n",a*b);
    printf("a/b: %d\n",a/b);
    printf("a%%b: %d\n",a%b);
    printf("a++: %d\n",a++);
    printf("++a: %d\n",++a);
    printf("a--: %d\n",a--);
    printf("--a: %d\n",--a);


}